# Generate WOTS+C known-answer tests (test/wots/vectors/wotsc.kat) from the
# authoritative reference implementation shrincs-bip/impl/shrincs.py.
#
# This is a MANUAL developer step: the produced .kat is committed to the
# repository, so `make test` / CI need neither Python nor a shrincs-bip
# checkout.  Regenerate when the construction or the reference changes:
#
#     python3 test/wots/gen_vectors.py \
#         --shrincs ../shrincs-bip/impl/shrincs.py \
#         -o test/wots/vectors/wotsc.kat
#
# The C side (test/wots/wots.c) reads the .kat and byte-compares the compiled
# shrincs_wots_pubkey_gen / shrincs_wots_sign / shrincs_wots_pubkey_from_sig outputs against
# these reference answers.

import argparse
import hashlib
import importlib.util
import subprocess
import sys
from pathlib import Path


def load_shrincs(path):
    spec = importlib.util.spec_from_file_location("shrincs", path)
    if spec is None or spec.loader is None:
        sys.exit(f"cannot load shrincs module from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def shrincs_commit(path):
    try:
        out = subprocess.run(
            ["git", "-C", str(Path(path).resolve().parent), "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=True,
        )
        return out.stdout.strip()
    except Exception:
        return "unknown"


def kdf(label, n):
    """Deterministic byte stretcher: SHA-256(label) blocks, truncated to n."""
    out = b""
    counter = 0
    while len(out) < n:
        out += hashlib.sha256(label + counter.to_bytes(4, "big")).digest()
        counter += 1
    return out[:n]


def cases():
    """(name, sk_seed[16], pk_seed[16], adrs[22], msg[32]) generator.

    Covers structured, all-zero, all-0xff, nonzero-height/index, and
    pseudorandom inputs."""
    yield ("sequential",
           bytes(range(16)), bytes(range(16, 32)),
           bytes(range(22)), bytes(range(32)))
    yield ("zeros",
           bytes(16), bytes(16), bytes(22), bytes(32))
    yield ("msg_all_ff",
           kdf(b"sk1", 16), kdf(b"pk1", 16), bytes(22), b"\xff" * 32)
    # nonzero height + 8-byte big-endian index prefix in the ADRS.
    adrs = bytearray(22)
    adrs[0] = 0x2A                      # height
    adrs[1:9] = (0x0011223344556677).to_bytes(8, "big")  # index
    yield ("nonzero_addr_prefix",
           kdf(b"sk2", 16), kdf(b"pk2", 16), bytes(adrs), kdf(b"msg2", 32))
    for i in range(4):
        lbl = str(i).encode()
        yield (f"random{i}",
               kdf(b"sk" + lbl, 16), kdf(b"pk" + lbl, 16),
               kdf(b"adrs" + lbl, 22), kdf(b"msg" + lbl, 32))


def main():
    ap = argparse.ArgumentParser(description="Generate WOTS+C KAT vectors from shrincs.py")
    ap.add_argument("--shrincs", default="../shrincs-bip/impl/shrincs.py",
                    help="path to shrincs-bip/impl/shrincs.py")
    ap.add_argument("-o", "--out", default="-", help="output file (default: stdout)")
    args = ap.parse_args()

    s = load_shrincs(args.shrincs)
    commit = shrincs_commit(args.shrincs)

    lines = []
    lines.append("# libshrincs WOTS+C known-answer tests")
    lines.append(f"# Generated by test/wots/gen_vectors.py from shrincs-bip/impl/shrincs.py @ {commit}")
    lines.append("# Construction: n=16, w=16, chain_count=32, constant_sum=240, 16-bit counter.")
    lines.append("# Fields per case (hex unless noted): sk_seed(16) pk_seed(16) adrs(22)")
    lines.append("#   msg(32) counter(decimal) digits(32) h_grind(16) sig(514) pk(16).")
    lines.append("# Cases are separated by blank lines; the parser checks on the pk line.")
    lines.append("")

    for name, sk_seed, pk_seed, adrs, msg in cases():
        assert len(sk_seed) == 16 and len(pk_seed) == 16
        assert len(adrs) == 22 and len(msg) == 32

        # Reference outputs (each call gets a fresh ADRS copy: shrincs
        # mutates it in place, exactly as the C clobbers addr[9..22)).
        counter, indexes = s.wots_c_grind_to_constant_sum(pk_seed, msg, bytearray(adrs))
        assert sum(indexes) == s.WOTS_C_CONSTANT_SUM
        assert 0 <= counter < 2**16

        # H_grind intermediate at the winning counter (grind-typed ADRS).
        ag = bytearray(adrs)
        ag[9] = s.SF_WOTS_C_GRIND
        h_grind = s.H_grind(pk_seed, ag, msg, counter)
        assert len(h_grind) == 16

        sig = s.wots_c_sign(msg, sk_seed, pk_seed, bytearray(adrs))
        pk = s.wots_c_pubkey_gen(sk_seed, pk_seed, bytearray(adrs))
        rec = s.wots_c_pubkey_from_sig(sig, msg, pk_seed, bytearray(adrs))
        assert len(sig) == 514 and len(pk) == 16
        assert rec == pk, f"{name}: recovered pk != pk"

        lines.append(f"# {name}")
        lines.append(f"sk_seed = {sk_seed.hex()}")
        lines.append(f"pk_seed = {pk_seed.hex()}")
        lines.append(f"adrs = {adrs.hex()}")
        lines.append(f"msg = {msg.hex()}")
        lines.append(f"counter = {counter}")
        lines.append(f"digits = {bytes(indexes).hex()}")
        lines.append(f"h_grind = {h_grind.hex()}")
        lines.append(f"sig = {sig.hex()}")
        lines.append(f"pk = {pk.hex()}")
        lines.append("")

    text = "\n".join(lines) + "\n"
    if args.out == "-":
        sys.stdout.write(text)
    else:
        Path(args.out).write_text(text)
        sys.stderr.write(f"wrote {args.out} ({len(list(cases()))} cases, shrincs @ {commit})\n")


if __name__ == "__main__":
    main()
