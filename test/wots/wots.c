static enum kat_result kat_chain_iter(const struct kat_case *c)
{
    uint8_t node[N];
    uint8_t pk_seed[N];
    uint8_t expected[N];
    uint8_t node_height = 0;
    uint64_t node_index = 0;
    unsigned long long start = 0;
    unsigned long long stop = 0;
    unsigned long long chain_index = 0;
    if (kat_bytes(c, "node", node, N) || kat_uint(c, "stop", WOTS_C_CHAIN_MAX, &stop) ||
        kat_uint(c, "start", stop, &start) || kat_bytes(c, "pk_seed", pk_seed, N) ||
        kat_anchor(c, "node_height", "node_index", &node_height, &node_index) ||
        kat_uint(c, "chain_index", UINT32_MAX, &chain_index) || kat_bytes(c, "output", expected, N)) {
        return KAT_MISMATCH;
    }
    shrincs_wots_c_chain_iter(
        node, (uint32_t)start, (uint32_t)stop, pk_seed, node_height, node_index, (uint32_t)chain_index);
    return kat_compare(node, expected, N);
}

/* The result is "counter : indexes", or "none". */
static enum kat_result kat_grind_to_constant_sum(const struct kat_case *c)
{
    uint8_t pk_seed[N];
    uint8_t message_digest[SHRINCS_WOTS_MSG_BYTES];
    uint8_t expected[WOTS_C_CHAIN_COUNT];
    uint8_t indexes[WOTS_C_CHAIN_COUNT];
    uint8_t node_height = 0;
    uint64_t node_index = 0;
    const char *output = kat_field(c, "output");
    if (!output || kat_bytes(c, "pk_seed", pk_seed, N) ||
        kat_bytes(c, "message_digest", message_digest, SHRINCS_WOTS_MSG_BYTES) ||
        kat_anchor(c, "node_height", "node_index", &node_height, &node_index)) {
        return KAT_MISMATCH;
    }
    int grinded = shrincs_wots_c_grind_to_constant_sum(indexes, pk_seed, message_digest, node_height, node_index);
    if (strcmp(output, "none") == 0) {
        return grinded < 0 ? KAT_AGREES : KAT_MISMATCH;
    }
    unsigned long long counter = 0;
    const char *rest = kat_number(output, UINT16_MAX, &counter);
    if (!rest || strncmp(rest, " : ", 3) != 0 || kat_list(rest + 3, expected, WOTS_C_CHAIN_COUNT)) {
        return KAT_MISMATCH;
    }
    if (grinded < 0 || (unsigned long long)grinded != counter) {
        return KAT_MISMATCH;
    }
    return kat_compare(indexes, expected, WOTS_C_CHAIN_COUNT);
}

/* The result is the indexes, or "none". */
static enum kat_result kat_map_digest(const struct kat_case *c)
{
    uint8_t pk_seed[N];
    uint8_t message_digest[SHRINCS_WOTS_MSG_BYTES];
    uint8_t expected[WOTS_C_CHAIN_COUNT];
    uint8_t indexes[WOTS_C_CHAIN_COUNT];
    uint8_t node_height = 0;
    uint64_t node_index = 0;
    unsigned long long counter = 0;
    const char *output = kat_field(c, "output");
    if (!output || kat_bytes(c, "pk_seed", pk_seed, N) ||
        kat_bytes(c, "message_digest", message_digest, SHRINCS_WOTS_MSG_BYTES) ||
        kat_anchor(c, "node_height", "node_index", &node_height, &node_index) ||
        kat_uint(c, "counter", UINT16_MAX, &counter)) {
        return KAT_MISMATCH;
    }
    int constant_sum =
        shrincs_wots_c_map_digest(indexes, pk_seed, message_digest, node_height, node_index, (uint32_t)counter);
    if (strcmp(output, "none") == 0) {
        return constant_sum == 0 ? KAT_AGREES : KAT_MISMATCH;
    }
    if (constant_sum == 0 || kat_list(output, expected, WOTS_C_CHAIN_COUNT)) {
        return KAT_MISMATCH;
    }
    return kat_compare(indexes, expected, WOTS_C_CHAIN_COUNT);
}

static enum kat_result kat_pubkey_gen(const struct kat_case *c)
{
    uint8_t sk_seed[SHRINCS_WOTS_SK_SEED_BYTES];
    uint8_t pk_seed[SHRINCS_WOTS_PK_SEED_BYTES];
    uint8_t expected[SHRINCS_WOTS_PK_BYTES];
    uint8_t pk[SHRINCS_WOTS_PK_BYTES];
    uint8_t node_height = 0;
    uint64_t node_index = 0;
    bool tree_balanced = false;
    uint8_t tree_depth = 0;
    if (kat_bytes(c, "sk_seed", sk_seed, sizeof sk_seed) || kat_bytes(c, "pk_seed", pk_seed, sizeof pk_seed) ||
        kat_anchor(c, "node_height", "node_index", &node_height, &node_index) ||
        kat_tree_shape(c, &tree_balanced, &tree_depth) || kat_bytes(c, "output", expected, sizeof expected)) {
        return KAT_MISMATCH;
    }
    shrincs_wots_c_pubkey_gen(pk, sk_seed, pk_seed, node_height, node_index, tree_balanced, tree_depth);
    return kat_compare(pk, expected, sizeof pk);
}

static enum kat_result kat_sign(const struct kat_case *c)
{
    uint8_t message_digest[SHRINCS_WOTS_MSG_BYTES];
    uint8_t sk_seed[SHRINCS_WOTS_SK_SEED_BYTES];
    uint8_t pk_seed[SHRINCS_WOTS_PK_SEED_BYTES];
    uint8_t expected[SHRINCS_WOTS_SIG_BYTES];
    uint8_t signature[SHRINCS_WOTS_SIG_BYTES];
    uint8_t node_height = 0;
    uint64_t node_index = 0;
    bool tree_balanced = false;
    uint8_t tree_depth = 0;
    const char *output = kat_field(c, "output");
    if (!output || kat_bytes(c, "message_digest", message_digest, sizeof message_digest) ||
        kat_bytes(c, "sk_seed", sk_seed, sizeof sk_seed) || kat_bytes(c, "pk_seed", pk_seed, sizeof pk_seed) ||
        kat_anchor(c, "node_height", "node_index", &node_height, &node_index) ||
        kat_tree_shape(c, &tree_balanced, &tree_depth)) {
        return KAT_MISMATCH;
    }
    int result = shrincs_wots_c_sign(
        signature, message_digest, sk_seed, pk_seed, node_height, node_index, tree_balanced, tree_depth);
    if (strcmp(output, "none") == 0) {
        return result == SHRINCS_SIGN_FAILED ? KAT_AGREES : KAT_MISMATCH;
    }
    if (result != SHRINCS_OK || kat_hex(output, expected, sizeof expected)) {
        return KAT_MISMATCH;
    }
    return kat_compare(signature, expected, sizeof signature);
}

static enum kat_result kat_pubkey_from_sig(const struct kat_case *c)
{
    uint8_t signature[SHRINCS_WOTS_SIG_BYTES];
    uint8_t message_digest[SHRINCS_WOTS_MSG_BYTES];
    uint8_t pk_seed[SHRINCS_WOTS_PK_SEED_BYTES];
    uint8_t expected[SHRINCS_WOTS_PK_BYTES];
    uint8_t pk[SHRINCS_WOTS_PK_BYTES];
    uint8_t node_height = 0;
    uint64_t node_index = 0;
    const char *output = kat_field(c, "output");
    if (!output || kat_bytes(c, "signature", signature, sizeof signature) ||
        kat_bytes(c, "message_digest", message_digest, sizeof message_digest) ||
        kat_bytes(c, "pk_seed", pk_seed, sizeof pk_seed) ||
        kat_anchor(c, "node_height", "node_index", &node_height, &node_index)) {
        return KAT_MISMATCH;
    }
    int result = shrincs_wots_c_pubkey_from_sig(pk, signature, message_digest, pk_seed, node_height, node_index);
    if (strcmp(output, "none") == 0) {
        return result == SHRINCS_VERIFY_FAILED ? KAT_AGREES : KAT_MISMATCH;
    }
    if (result != SHRINCS_OK || kat_hex(output, expected, sizeof expected)) {
        return KAT_MISMATCH;
    }
    return kat_compare(pk, expected, sizeof pk);
}

/* A function name the table does not know is a mismatch, never a skipped check. */
static enum kat_result kat_check(const struct kat_case *c)
{
    static const struct {
        const char *function;
        enum kat_result (*check)(const struct kat_case *);
    } table[] = {
        {"base_2b", kat_base_2b},
        {"F", kat_f},
        {"PRF", kat_prf},
        {"T_sf", kat_t_sf},
        {"H_grind", kat_h_grind},
        {"wots_c_chain_iter", kat_chain_iter},
        {"wots_c_grind_to_constant_sum", kat_grind_to_constant_sum},
        {"wots_c_map_digest", kat_map_digest},
        {"wots_c_pubkey_gen", kat_pubkey_gen},
        {"wots_c_sign", kat_sign},
        {"wots_c_pubkey_from_sig", kat_pubkey_from_sig},
    };
    const char *function = kat_field(c, "function");
    if (!function) {
        return KAT_MISMATCH;
    }
    for (size_t i = 0; i < sizeof table / sizeof table[0]; i++) {
        if (strcmp(function, table[i].function) == 0) {
            enum kat_result result = table[i].check(c);
            if (result == KAT_MISMATCH) {
                (void)fprintf(stderr, "  kat: %s disagrees with the reference or its case is malformed\n", function);
            }
            return result;
        }
    }
    (void)fprintf(stderr, "  kat: unknown function %s\n", function);
    return KAT_MISMATCH;
}

/* Check every case of the file. Returns -1 on the first mismatch or on a file that cannot be
   read, else 0, with the number of cases that agree and of cases the C does not have. */
static int run_wots_kat(const char *path, int *agree, int *absent)
{
    *agree = 0;
    *absent = 0;
    FILE *f = fopen(path, "r");
    if (!f) {
        (void)fprintf(stderr, "  kat: cannot open %s\n", path);
        return -1;
    }
    struct kat_case c = {0};
    char *line = NULL;
    size_t capacity = 0;
    int rc = 0;
    int at_end = 0;
    while (rc == 0 && !at_end) {
        at_end = getline(&line, &capacity, f) <= 0;
        int blank = at_end || line[0] == '\n' || line[0] == '\r';
        if (!blank && line[0] != '#') {
            rc = kat_add(&c, line);
        } else if (blank && c.count > 0) {
            enum kat_result result = kat_check(&c);
            if (result == KAT_MISMATCH) {
                rc = -1;
            } else if (result == KAT_ABSENT) {
                (*absent)++;
            } else {
                (*agree)++;
            }
            kat_clear(&c);
        }
    }
    kat_clear(&c);
    free(line);
    (void)fclose(f);
    return rc;
}

/* ---------- Self-consistency ----------

   Fresh random inputs on every run: sign, then check that the public key recovered from the
   signature is the generated one. Signing can in principle fail (SHRINCS_SIGN_FAILED) if
   2^16 counters are exhausted without hitting the constant digit sum; that is negligible, so
   treating it as T_ERROR flags a broken grinding loop rather than a spurious FAIL. */

struct wots_inputs {
    uint8_t sk_seed[SHRINCS_WOTS_SK_SEED_BYTES];
    uint8_t pk_seed[SHRINCS_WOTS_PK_SEED_BYTES];
    uint8_t message_digest[SHRINCS_WOTS_MSG_BYTES];
    uint8_t node_height;
    uint64_t node_index;
    bool tree_balanced;
    uint8_t tree_depth;
};

static int random_inputs(struct wots_inputs *in)
{
    uint8_t raw[11];
    if (fill_random(in->sk_seed, sizeof in->sk_seed) || fill_random(in->pk_seed, sizeof in->pk_seed) ||
        fill_random(in->message_digest, sizeof in->message_digest) || fill_random(raw, sizeof raw)) {
        return -1;
    }
    in->node_height = raw[0];
    in->node_index = 0;
    for (int i = 0; i < 8; i++) {
        in->node_index = (in->node_index << 8) | raw[1 + i];
    }
    in->tree_balanced = (raw[9] & 1) != 0;
    in->tree_depth = raw[10];
    return 0;
}

static void keygen(uint8_t pk[SHRINCS_WOTS_PK_BYTES], const struct wots_inputs *in)
{
    shrincs_wots_c_pubkey_gen(
        pk, in->sk_seed, in->pk_seed, in->node_height, in->node_index, in->tree_balanced, in->tree_depth);
}

static int sign(uint8_t signature[SHRINCS_WOTS_SIG_BYTES], const struct wots_inputs *in)
{
    return shrincs_wots_c_sign(signature,
                               in->message_digest,
                               in->sk_seed,
                               in->pk_seed,
                               in->node_height,
                               in->node_index,
                               in->tree_balanced,
                               in->tree_depth);
}

/* Verification as a caller does it: recover the public key and compare. */
static int verifies(const uint8_t pk[SHRINCS_WOTS_PK_BYTES],
                    const uint8_t signature[SHRINCS_WOTS_SIG_BYTES],
                    const struct wots_inputs *in)
{
    uint8_t recovered[SHRINCS_WOTS_PK_BYTES];
    if (shrincs_wots_c_pubkey_from_sig(
            recovered, signature, in->message_digest, in->pk_seed, in->node_height, in->node_index) != SHRINCS_OK) {
        return 0;
    }
    return memcmp(recovered, pk, SHRINCS_WOTS_PK_BYTES) == 0;
}

static enum test_status roundtrip(const struct wots_inputs *in)
{
    uint8_t pk[SHRINCS_WOTS_PK_BYTES];
    uint8_t signature[SHRINCS_WOTS_SIG_BYTES];
    keygen(pk, in);
    if (sign(signature, in) != SHRINCS_OK) {
        return T_ERROR;
    }
    return verifies(pk, signature, in) ? T_OK : T_FAIL;
}

static enum test_status test_wots_self_roundtrip(void)
{
    struct wots_inputs in;
    if (random_inputs(&in)) {
        return T_ERROR;
    }
    return roundtrip(&in);
}

/* All-zero digest: an extreme digit distribution the grinding must still push to the constant
   target sum. */
static enum test_status test_wots_msg_all_zero(void)
{
    struct wots_inputs in;
    if (random_inputs(&in)) {
        return T_ERROR;
    }
    memset(in.message_digest, 0, sizeof in.message_digest);
    return roundtrip(&in);
}

/* All-0xff digest: the opposite extreme distribution. */
static enum test_status test_wots_msg_all_ff(void)
{
    struct wots_inputs in;
    if (random_inputs(&in)) {
        return T_ERROR;
    }
    memset(in.message_digest, 0xff, sizeof in.message_digest);
    return roundtrip(&in);
}

/* Signing is deterministic (grinding picks the least valid counter), so two signatures over
   the same inputs must be byte-identical. */
static enum test_status test_wots_sign_twice(void)
{
    struct wots_inputs in;
    uint8_t first[SHRINCS_WOTS_SIG_BYTES];
    uint8_t second[SHRINCS_WOTS_SIG_BYTES];
    if (random_inputs(&in)) {
        return T_ERROR;
    }
    if (sign(first, &in) != SHRINCS_OK || sign(second, &in) != SHRINCS_OK) {
        return T_ERROR;
    }
    return memcmp(first, second, SHRINCS_WOTS_SIG_BYTES) == 0 ? T_OK : T_FAIL;
}

/* ---------- Tamper checks ----------

   Each test signs honestly, changes one input of the verifier, and requires that the public
   key no longer verifies. */

enum tamper { TAMPER_CHAIN, TAMPER_COUNTER, TAMPER_MESSAGE, TAMPER_PK_SEED, TAMPER_NODE_INDEX, TAMPER_NODE_HEIGHT };

static enum test_status tampered(enum tamper what)
{
    struct wots_inputs in;
    uint8_t pk[SHRINCS_WOTS_PK_BYTES];
    uint8_t signature[SHRINCS_WOTS_SIG_BYTES];
    if (random_inputs(&in)) {
        return T_ERROR;
    }
    keygen(pk, &in);
    if (sign(signature, &in) != SHRINCS_OK) {
        return T_ERROR;
    }
    switch (what) {
        case TAMPER_CHAIN:
            signature[300] ^= 0x10; /* a chain byte (the signature is 2 + 32*16 bytes) */
            break;
        case TAMPER_COUNTER:
            signature[1] ^= 0x01; /* the grinding counter is the first two bytes */
            break;
        case TAMPER_MESSAGE:
            in.message_digest[0] ^= 0x01;
            break;
        case TAMPER_PK_SEED:
            in.pk_seed[7] ^= 0x80;
            break;
        case TAMPER_NODE_INDEX:
            in.node_index ^= 1;
            break;
        case TAMPER_NODE_HEIGHT:
            in.node_height ^= 1;
            break;
    }
    return verifies(pk, signature, &in) ? T_FAIL : T_OK;
}

static enum test_status test_wots_tamper_sig(void)
{
    return tampered(TAMPER_CHAIN);
}

static enum test_status test_wots_tamper_counter(void)
{
    return tampered(TAMPER_COUNTER);
}

static enum test_status test_wots_tamper_msg(void)
{
    return tampered(TAMPER_MESSAGE);
}

static enum test_status test_wots_tamper_pk_seed(void)
{
    return tampered(TAMPER_PK_SEED);
}

static enum test_status test_wots_wrong_index(void)
{
    return tampered(TAMPER_NODE_INDEX);
}

static enum test_status test_wots_wrong_height(void)
{
    return tampered(TAMPER_NODE_HEIGHT);
}

int run_wots_tests(void)
{
    int failures = 0;
    (void)printf("wots+c (grinding / constant-sum Winternitz)\n");

    int agree = 0;
    int absent = 0;
    if (run_wots_kat("test/spec/vectors/wots_c.kat", &agree, &absent) == 0 && agree > 0) {
        (void)printf("  %-28s ... ok (%d cases, %d more outside what the C implements)\n",
                     "test_wots_kat_reference",
                     agree,
                     absent);
    } else {
        (void)printf("  %-28s ... FAIL (after %d ok)\n", "test_wots_kat_reference", agree);
        failures++;
    }

    RUN(test_wots_self_roundtrip);
    RUN(test_wots_msg_all_zero);
    RUN(test_wots_msg_all_ff);
    RUN(test_wots_sign_twice);
    RUN(test_wots_tamper_msg);
    RUN(test_wots_tamper_sig);
    RUN(test_wots_tamper_counter);
    RUN(test_wots_tamper_pk_seed);
    RUN(test_wots_wrong_index);
    RUN(test_wots_wrong_height);
    return failures;
}
