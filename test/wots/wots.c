/* WOTS+C tests: the reference vectors, then self-consistency and tamper checks.

   The vectors name functions that src/wots.c keeps static, so this file includes that source
   and calls them directly. The test binary therefore runs this copy of the WOTS+C code, built
   with the compiler and flags of the library, and takes the tweakable hash, SHA-256 and the
   byte helpers from the library itself. */

#include "common.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "../../src/wots.c" /* NOLINT(bugprone-suspicious-include) */

/* ---------- Reference vectors ----------

   test/spec/vectors/wots_c.kat is generated by test/spec/gen_vectors.py from the reference
   implementation shrincs-bip/impl/shrincs.py, and `dune build @test/spec-test` checks proof/spec.v against
   the same file. One case is a block of "name = value" lines: the function, its arguments in
   the order of the Python signature, and its result. */

enum { KAT_MAX_FIELDS = 12 };

struct kat_case {
    int count;
    char *name[KAT_MAX_FIELDS];
    char *value[KAT_MAX_FIELDS];
};

/* What a case came to. A case the C has no code for is KAT_ABSENT, never an error: the file
   is shared with the specification, whose base_2b is general where the C's is one instance. */
enum kat_result { KAT_MISMATCH = -1, KAT_ABSENT = 0, KAT_AGREES = 1 };

static void kat_clear(struct kat_case *c)
{
    for (int i = 0; i < c->count; i++) {
        free(c->name[i]);
        free(c->value[i]);
    }
    c->count = 0;
}

static char *kat_copy(const char *text, size_t length)
{
    char *copy = malloc(length + 1);
    if (copy) {
        memcpy(copy, text, length);
        copy[length] = '\0';
    }
    return copy;
}

/* Add one "name = value" line to the case. Returns -1 on a line of another shape. */
static int kat_add(struct kat_case *c, const char *line)
{
    const char *separator = strstr(line, " = ");
    if (!separator || c->count == KAT_MAX_FIELDS) {
        return -1;
    }
    const char *value = separator + 3;
    size_t value_length = strcspn(value, "\r\n");
    char *name_copy = kat_copy(line, (size_t)(separator - line));
    char *value_copy = kat_copy(value, value_length);
    if (!name_copy || !value_copy) {
        free(name_copy);
        free(value_copy);
        return -1;
    }
    c->name[c->count] = name_copy;
    c->value[c->count] = value_copy;
    c->count++;
    return 0;
}

static const char *kat_field(const struct kat_case *c, const char *name)
{
    for (int i = 0; i < c->count; i++) {
        if (strcmp(c->name[i], name) == 0) {
            return c->value[i];
        }
    }
    (void)fprintf(stderr, "  kat: a case has no field %s\n", name);
    return NULL;
}

static int kat_hex_nibble(unsigned char c)
{
    if (c >= '0' && c <= '9') {
        return c - '0';
    }
    if (c >= 'a' && c <= 'f') {
        return 10 + (c - 'a');
    }
    return -1;
}

/* Decode a hex string of exactly n bytes. */
static int kat_hex(const char *text, uint8_t *out, size_t n)
{
    if (!text || strlen(text) != 2 * n) {
        return -1;
    }
    for (size_t i = 0; i < n; i++) {
        int hi = kat_hex_nibble((unsigned char)text[2 * i]);
        int lo = kat_hex_nibble((unsigned char)text[(2 * i) + 1]);
        if (hi < 0 || lo < 0) {
            return -1;
        }
        out[i] = (uint8_t)((hi << 4) | lo);
    }
    return 0;
}

static int kat_bytes(const struct kat_case *c, const char *name, uint8_t *out, size_t n)
{
    return kat_hex(kat_field(c, name), out, n);
}

/* Parse a decimal integer that is at most max and ends at the end of the string or at a
   space. Returns the first character after it, or NULL. */
static const char *kat_number(const char *text, unsigned long long max, unsigned long long *out)
{
    if (!text || *text < '0' || *text > '9') {
        return NULL;
    }
    char *end = NULL;
    unsigned long long value = strtoull(text, &end, 10);
    if ((*end != '\0' && *end != ' ') || value > max) {
        return NULL;
    }
    *out = value;
    return end;
}

static int kat_uint(const struct kat_case *c, const char *name, unsigned long long max, unsigned long long *out)
{
    const char *end = kat_number(kat_field(c, name), max, out);
    return (end && *end == '\0') ? 0 : -1;
}

/* Parse exactly n integers below 256, separated by single spaces. */
static int kat_list(const char *text, uint8_t *out, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        unsigned long long value = 0;
        text = kat_number(text, 255, &value);
        if (!text || *text != (i + 1 < n ? ' ' : '\0')) {
            return -1;
        }
        out[i] = (uint8_t)value;
        text++;
    }
    return 0;
}

/* The two fields every address carries, under the names the case uses for them. */
static int
kat_anchor(const struct kat_case *c, const char *height_name, const char *index_name, uint8_t *height, uint64_t *index)
{
    unsigned long long h = 0;
    unsigned long long i = 0;
    if (kat_uint(c, height_name, UINT8_MAX, &h) || kat_uint(c, index_name, UINT64_MAX, &i)) {
        return -1;
    }
    *height = (uint8_t)h;
    *index = (uint64_t)i;
    return 0;
}

static int kat_tree_shape(const struct kat_case *c, bool *tree_balanced, uint8_t *tree_depth)
{
    unsigned long long balanced = 0;
    unsigned long long depth = 0;
    if (kat_uint(c, "tree_balanced", 1, &balanced) || kat_uint(c, "tree_depth", UINT8_MAX, &depth)) {
        return -1;
    }
    *tree_balanced = balanced != 0;
    *tree_depth = (uint8_t)depth;
    return 0;
}

static enum kat_result kat_compare(const uint8_t *got, const uint8_t *expected, size_t n)
{
    return memcmp(got, expected, n) == 0 ? KAT_AGREES : KAT_MISMATCH;
}

/* The C has base_2b at one instance only: b = WOTS_C_CHAIN_BITS over N bytes. */
static enum kat_result kat_base_2b(const struct kat_case *c)
{
    unsigned long long b = 0;
    unsigned long long outlen = 0;
    const char *x_text = kat_field(c, "x");
    if (!x_text || kat_uint(c, "b", UINT8_MAX, &b) || kat_uint(c, "outlen", UINT8_MAX, &outlen)) {
        return KAT_MISMATCH;
    }
    if (b != WOTS_C_CHAIN_BITS || outlen != WOTS_C_CHAIN_COUNT || strlen(x_text) != 2 * (size_t)N) {
        return KAT_ABSENT;
    }
    uint8_t x[N];
    uint8_t expected[WOTS_C_CHAIN_COUNT];
    uint8_t indexes[WOTS_C_CHAIN_COUNT];
    if (kat_hex(x_text, x, N) || kat_list(kat_field(c, "output"), expected, WOTS_C_CHAIN_COUNT)) {
        return KAT_MISMATCH;
    }
    shrincs_wots_c_base_2b(indexes, x);
    return kat_compare(indexes, expected, WOTS_C_CHAIN_COUNT);
}

static enum kat_result kat_f(const struct kat_case *c)
{
    uint8_t pk_seed[N];
    uint8_t m_1[N];
    uint8_t expected[N];
    uint8_t out[N];
    uint8_t height = 0;
    uint64_t index = 0;
    unsigned long long chain_index = 0;
    unsigned long long hash_index = 0;
    if (kat_bytes(c, "pk_seed", pk_seed, N) || kat_anchor(c, "height", "index", &height, &index) ||
        kat_uint(c, "chain_index", UINT32_MAX, &chain_index) || kat_uint(c, "hash_index", UINT32_MAX, &hash_index) ||
        kat_bytes(c, "M_1", m_1, N) || kat_bytes(c, "output", expected, N)) {
        return KAT_MISMATCH;
    }
    shrincs_wots_c_f(out, pk_seed, height, index, (uint32_t)chain_index, (uint32_t)hash_index, m_1);
    return kat_compare(out, expected, N);
}

